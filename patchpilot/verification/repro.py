"""Turn an AI finding's claimed failing input into a pytest file, deterministically.

The AI said: `paginate(list(range(1, 13)), 1)` should be `[1..10]`. We don't ask the AI
to write that test: we build it ourselves from the claim, so the test is exactly the
claim and nothing else. If the claim can't be expressed as `call == literal`, return
None and the caller falls back to the model-written test.
"""

from __future__ import annotations

import ast
import re

from patchpilot.ingestion.loader import SourceFile

ALIAS = "module_under_test"


def _module_names(sf: SourceFile) -> set[str]:
    names: set[str] = set()
    for node in ast.parse(sf.content).body:
        if isinstance(node, ast.FunctionDef | ast.AsyncFunctionDef | ast.ClassDef):
            names.add(node.name)
        elif isinstance(node, ast.Assign):
            names |= {t.id for t in node.targets if isinstance(t, ast.Name)}
        elif isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
            names.add(node.target.id)
        elif isinstance(node, ast.Import | ast.ImportFrom):
            names |= {(a.asname or a.name).split(".")[0] for a in node.names}
    return names


class _Qualify(ast.NodeTransformer):
    def __init__(self, names: set[str]):
        self.names = names

    def visit_Name(self, node: ast.Name) -> ast.AST:
        if node.id in self.names and isinstance(node.ctx, ast.Load):
            return ast.copy_location(ast.Attribute(ast.Name(ALIAS, ast.Load()), node.id, ast.Load()), node)
        return node


def build_repro_test(sf: SourceFile, module: str, call: str, expected: str, label: str) -> str | None:
    try:
        expr = ast.parse(call.strip(), mode="eval")
        value = ast.literal_eval(expected.strip())
    except (SyntaxError, ValueError, TypeError, MemoryError, RecursionError):
        return None
    if not isinstance(expr.body, ast.Call):
        return None
    qualified = ast.unparse(ast.fix_missing_locations(_Qualify(_module_names(sf)).visit(expr)))
    expected_src = f"pytest.approx({value!r})" if isinstance(value, float) else repr(value)
    name = re.sub(r"\W+", "_", label).strip("_").lower() or "defect"
    return (
        '"""Reproduction test generated by PatchPilot from the reported failing input."""\n\n'
        "import pytest\n\n"
        f"import {module} as {ALIAS}\n\n\n"
        f"def test_{name}_repro():\n"
        f"    assert {qualified} == {expected_src}\n"
    )
